/**
 * Generate this bundle's `cordis.patch.yml` from the INSTALLED dsh preset
 * files, so we never hand-copy a preset.
 *
 * What it emits:
 *   1. an `insert` row mounting this package's host half (`dsh-malko-prefs`);
 *   2. one top-level override per shipped preset (`preset-ptc`,
 *      `preset-standard`), copied verbatim from the installed preset except
 *      that the `compaction-basic` row is retargeted at
 *      `dsh-malko-prefs/compaction` (our tunable engine).
 *
 * Why: a patch replaces a row's `config` wholesale, and `compaction-basic`
 * lives nested inside the preset's `plugins` list — so the only supported way
 * to swap the backend is to restate the whole preset. Doing it from the
 * installed files keeps the copy in sync and makes regeneration a one-liner:
 *
 *   node scripts/gen-preset-override.mjs <presets-dir>
 *
 * `<presets-dir>` defaults to `$DSH_PRESETS_DIR`, then to the well-known
 * location inside the global dsh install on this machine.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const PACKAGE = 'dsh-malko-prefs'
const ENGINE = `${PACKAGE}/compaction`
const BASE_ENGINE = '@deepseek-ai/dsh-compaction-basic'

const DEFAULT_PRESETS_DIR = join(
  '/home/aibox/.nvm/versions/node/v24.13.1/lib/node_modules/@deepseek-ai/dsh/node_modules/@deepseek-ai/dsh-web-app/presets',
)

const presetsDir = process.argv[2] ?? process.env.DSH_PRESETS_DIR ?? DEFAULT_PRESETS_DIR
if (!existsSync(presetsDir)) {
  console.error(`gen-preset-override: presets dir not found: ${presetsDir}`)
  console.error('usage: node scripts/gen-preset-override.mjs <presets-dir>')
  process.exit(1)
}

/** De-indent one `- insert:` item (4 spaces) and retarget the compaction engine. */
function overrideRow(file) {
  const path = join(presetsDir, file)
  const lines = readFileSync(path, 'utf8').split('\n')
  const start = lines.findIndex((line) => /^ {4}- id: preset-/.test(line))
  if (start === -1) throw new Error(`gen-preset-override: no "    - id: preset-*" row in ${path}`)
  const body = lines
    .slice(start)
    .map((line) => (line.startsWith('    ') ? line.slice(4) : line))
    .join('\n')
    .trimEnd()
  if (!body.includes(`name: '${BASE_ENGINE}'`)) {
    throw new Error(`gen-preset-override: ${path} does not reference ${BASE_ENGINE}`)
  }
  return body.replace(`name: '${BASE_ENGINE}'`, `name: '${ENGINE}'`)
}

const header = `# dsh-malko-prefs bundle layer (GENERATED by scripts/gen-preset-override.mjs).
#
# Do not edit by hand: regenerate with
#   node scripts/gen-preset-override.mjs <presets-dir>
# after a dsh upgrade that changes @deepseek-ai/dsh-web-app/presets/*.patch.yml.
#
# 1) mount the host half (settings + llama.cpp probe);
# 2) restate each shipped agent preset, swapping the official compaction-basic
#    backend for dsh-malko-prefs/compaction (our tunable wrapper of the same
#    engine), keeping command-compact and tool-result-pruner untouched.
`

const host = `- insert:\n    - id: malko-prefs\n      name: '${PACKAGE}'\n`
// Every shipped preset that mounts the official compaction backend.
const presetFiles = readdirSync(presetsDir)
  .filter((file) => file.endsWith('.patch.yml'))
  .filter((file) => readFileSync(join(presetsDir, file), 'utf8').includes(BASE_ENGINE))
  .sort()
if (presetFiles.length === 0) throw new Error(`gen-preset-override: no preset references ${BASE_ENGINE} in ${presetsDir}`)
const rows = presetFiles.map(overrideRow).join('\n')

writeFileSync('cordis.patch.yml', `${header}${host}${rows}\n`)
console.log(`wrote cordis.patch.yml (overriding ${presetFiles.join(', ')})`)
